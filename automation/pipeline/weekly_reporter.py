"""
Weekly Performance & Buffer Health Reporter for WhereMyDollarGo
Runs every Sunday on GitHub Actions.
Generates weekly-report.md and creates a GitHub Issue for 1-click mobile/browser check-in.
"""
import os
import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
PIPELINE_DIR = ROOT / "automation" / "pipeline"

def generate_weekly_report():
    state_file = PIPELINE_DIR / "state.json"
    topics_file = PIPELINE_DIR / "topics.json"

    with open(topics_file, encoding="utf-8") as f:
        topics_data = json.load(f)

    state = {}
    if state_file.exists():
        with open(state_file, encoding="utf-8") as f:
            state = json.load(f)

    scheduled = state.get("scheduled_slots", {})
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    total_slots = len(scheduled)
    published_count = sum(1 for s in scheduled.values() if s.get("status") == "PUBLISHED" or s.get("youtube_id"))
    staged_count = sum(1 for s in scheduled.values() if s.get("status") != "PUBLISHED" and not s.get("youtube_id"))

    # Build report markdown
    report_lines = [
        f"# 📊 WhereMyDollarGo: Weekly Executive Report ({now_str})",
        "",
        "## 1. System Health & Autonomous Status",
        "- **Cloud Pipeline**: Online & Active (GitHub Actions)",
        f"- **Channel**: `{state.get('channel_handle', '@WhereMyDollarGo')}`",
        f"- **Total Content Slots Managed**: {total_slots}",
        f"- **Videos Published to YouTube**: {published_count}",
        f"- **Ready in Publish Queue**: {staged_count}",
        "",
        "## 2. Recent Production Slots & Visual Styles",
        "| Slot Date | Title | Visual Style | Status |",
        "|---|---|---|---|"
    ]

    for slot_id, data in list(scheduled.items())[-14:]:
        stat = "✅ Live on YouTube" if data.get("youtube_id") else "📦 Staged in Repo"
        report_lines.append(f"| {data.get('publish_at', slot_id)[:10]} | {data.get('title')} | {data.get('style')} | {stat} |")

    report_lines.extend([
        "",
        "## 3. Next Week's Upcoming Queue",
        "The autonomous pipeline has pre-loaded upcoming finance topics in `topics.json`.",
        "- Daily Carousel: *Last 24 Hours in US Money* generated at 07:00 ET",
        "- Daily Shorts: 12:00 ET and 18:00 ET slots running automatically.",
        "",
        "---",
        "*Automated report generated by WhereMyDollarGo Cloud Agent.*"
    ])

    report_content = "\n".join(report_lines)

    report_file = ROOT / "weekly-report.md"
    with open(report_file, "w", encoding="utf-8") as f:
        f.write(report_content)

    print("Generated weekly-report.md")

    # If running in GitHub Actions with GITHUB_TOKEN, create or update a GitHub issue for easy viewing on mobile/browser
    gh_token = os.environ.get("GITHUB_TOKEN")
    gh_repo = os.environ.get("GITHUB_REPOSITORY")
    if gh_token and gh_repo:
        try:
            issue_title = f"Weekly Channel Status & Health Report: {now_str}"
            subprocess.run([
                "gh", "issue", "create",
                "--repo", gh_repo,
                "--title", issue_title,
                "--body", report_content
            ], check=False)
            print("Successfully posted weekly report as a GitHub Issue.")
        except Exception as e:
            print(f"Could not post GitHub issue: {e}")

if __name__ == "__main__":
    generate_weekly_report()
